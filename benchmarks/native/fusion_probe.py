#!/usr/bin/env python3
"""Quantify the throughput left on the table by un-fused multi-stage pipelines.

Lockstep's optimizer already plans stage fusion: for the ``multi_stage_pipeline``
workload it reports ``alertsActive = FUSED[Normalize -> Score -> KeepActive]``
with ``eliminated_intermediates: [eventsEnriched, alertsScored]``. But the code
generator only emits that single fused loop when
``codegen._can_vectorize_fused_group`` returns true, and that check bails out on
any group whose kernel takes an ``accum`` parameter::

    if param.modifier == "accum":
        return False

``multi_stage_pipeline`` (the ``Score`` stage) and ``telemetry_filter_aggregation``
(the ``AggregateReadings`` stage) both accumulate, so they fall back to one
strip-mined loop *per stage*. Each stage streams the whole arena, materializing
the intermediate streams the optimizer said it would eliminate -- several passes
over memory instead of one.

This probe measures the size of that gap. It runs the multi_stage computation
two ways over identical SoA data:

* ``unfused`` -- three separate loops that write and re-read the intermediate
  streams and a per-row accumulator array, mirroring what codegen emits today.
* ``fused`` -- one loop that carries intermediates in registers and accumulates
  on the fly, writing only the final output. This is what the optimizer's
  ``FUSED[...]`` plan describes.

Both produce identical results (checked), so the delta is purely the cost of the
extra memory passes -- i.e. the throughput a fusion-through-accumulators codegen
improvement would recover. Built with ``clang -O3 -march=native -ffast-math``
(matching Lockstep's reduction codegen); read the ratio, not the absolutes.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

DEFAULT_SIZES = (4_000, 16_000, 64_000, 256_000, 1_000_000)


class BenchmarkError(RuntimeError):
    pass


# SoA columns for the multi_stage workload's structs. Both variants use the same
# layout, so the only difference measured is stage fusion (memory passes), not
# AoS-vs-SoA (that is benchmarked separately in soa_vs_aos.py).
_C_SOURCE = r"""/* Auto-generated by benchmarks/native/fusion_probe.py -- do not edit. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

static double now_ns(void) {
    struct timespec t;
    clock_gettime(CLOCK_MONOTONIC, &t);
    return (double)t.tv_sec * 1e9 + (double)t.tv_nsec;
}

static float *fvec(size_t n) { return (float *)aligned_alloc(64, n * sizeof(float)); }
static int32_t *ivec(size_t n) { return (int32_t *)aligned_alloc(64, n * sizeof(int32_t)); }
static uint8_t *bvec(size_t n) { return (uint8_t *)aligned_alloc(64, n * sizeof(uint8_t)); }

int main(int argc, char **argv) {
    if (argc < 3) { fprintf(stderr, "usage: %s N ITERS\n", argv[0]); return 2; }
    size_t n = (size_t)strtoull(argv[1], NULL, 10);
    int iters = atoi(argv[2]);

    /* Inputs (eventsRaw) */
    int32_t *raw_dev = ivec(n);
    float   *raw_val = fvec(n);
    uint8_t *raw_act = bvec(n);
    /* Final output (alertsActive) */
    int32_t *out_dev = ivec(n);
    float   *out_score = fvec(n);
    uint8_t *out_act = bvec(n);
    /* Intermediates the unfused path materializes (optimizer eliminates these) */
    float   *enr_norm = fvec(n);
    int32_t *enr_dev = ivec(n);
    uint8_t *enr_act = bvec(n);
    float   *scr_score = fvec(n);
    int32_t *scr_dev = ivec(n);
    uint8_t *scr_act = bvec(n);
    float   *acc_score = fvec(n);   /* per-row accumulator partials */
    int32_t *acc_count = ivec(n);

    if (!raw_dev || !out_score || !enr_norm || !scr_score || !acc_score) {
        fprintf(stderr, "alloc failed\n"); return 2;
    }

    for (size_t i = 0; i < n; ++i) {
        raw_dev[i] = (int32_t)i;
        raw_val[i] = (float)(i % 1000) * 0.01f;
        raw_act[i] = (uint8_t)(i & 1u);
    }

    volatile float sink = 0.0f;
    double t;

    /* ---- unfused: three passes, writing + re-reading intermediates ---- */
    float unfused_score = 0.0f;
    int32_t unfused_count = 0;
    for (int k = 0; k < iters + 3; ++k) {
        if (k == 3) t = now_ns();
        for (size_t i = 0; i < n; ++i) {           /* Normalize */
            enr_dev[i] = raw_dev[i];
            enr_norm[i] = raw_val[i] * 0.1f;
            enr_act[i] = raw_act[i];
        }
        for (size_t i = 0; i < n; ++i) {           /* Score (+ accumulate) */
            float s = enr_norm[i] * 1.6f;
            scr_dev[i] = enr_dev[i];
            scr_score[i] = s;
            scr_act[i] = enr_act[i];
            acc_score[i] = s;
            acc_count[i] = 1;
        }
        for (size_t i = 0; i < n; ++i) {           /* KeepActive (copy) */
            out_dev[i] = scr_dev[i];
            out_score[i] = scr_score[i];
            out_act[i] = scr_act[i];
        }
        float sacc = 0.0f; int32_t cacc = 0;       /* fold sum */
        for (size_t i = 0; i < n; ++i) { sacc += acc_score[i]; cacc += acc_count[i]; }
        unfused_score = sacc; unfused_count = cacc;
    }
    double unfused_ns = (now_ns() - t) / iters;
    sink += out_score[n / 2] + unfused_score;

    /* ---- fused: one pass, intermediates in registers, accumulate on the fly ---- */
    float fused_score = 0.0f;
    int32_t fused_count = 0;
    for (int k = 0; k < iters + 3; ++k) {
        if (k == 3) t = now_ns();
        float sacc = 0.0f; int32_t cacc = 0;
        for (size_t i = 0; i < n; ++i) {
            float norm = raw_val[i] * 0.1f;
            float s = norm * 1.6f;
            out_dev[i] = raw_dev[i];
            out_score[i] = s;
            out_act[i] = raw_act[i];
            sacc += s;
            cacc += 1;
        }
        fused_score = sacc; fused_count = cacc;
    }
    double fused_ns = (now_ns() - t) / iters;
    sink += out_score[n / 2] + fused_score;
    (void)sink;

    printf(
        "{\"n\": %zu, \"unfused_ns\": %.1f, \"fused_ns\": %.1f, "
        "\"unfused_score\": %.3f, \"fused_score\": %.3f, "
        "\"unfused_count\": %d, \"fused_count\": %d, "
        "\"out_score_mid\": %.6f}\n",
        n, unfused_ns, fused_ns, unfused_score, fused_score,
        unfused_count, fused_count, out_score[n / 2]);
    return 0;
}
"""


def _iterations_for(n: int) -> int:
    return max(20, min(20000, 200_000_000 // max(n, 1)))


def _build(clang: str, work_dir: Path) -> Path:
    src = work_dir / "fusion_probe.c"
    exe = work_dir / "fusion_probe"
    src.write_text(_C_SOURCE, encoding="utf-8")
    cmd = [clang, "-O3", "-march=native", "-ffast-math", str(src), "-o", str(exe), "-lm"]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        raise BenchmarkError(f"clang failed ({proc.returncode})\n{proc.stderr.strip()}")
    return exe


def _run_size(exe: Path, n: int) -> dict[str, float]:
    iters = _iterations_for(n)
    run = subprocess.run(
        [str(exe), str(n), str(iters)], capture_output=True, text=True, timeout=300
    )
    if run.returncode != 0:
        raise BenchmarkError(f"probe failed for n={n} ({run.returncode})\n{run.stderr.strip()}")
    try:
        return json.loads(run.stdout.strip().splitlines()[-1])
    except (json.JSONDecodeError, IndexError) as exc:
        raise BenchmarkError(f"could not parse probe output for n={n}: {run.stdout!r}") from exc


def _results_agree(raw: dict[str, float]) -> bool:
    def close(a: float, b: float) -> bool:
        scale = max(1.0, abs(a), abs(b))
        return abs(a - b) <= 1e-3 * scale

    return (
        close(raw["unfused_score"], raw["fused_score"])
        and int(raw["unfused_count"]) == int(raw["fused_count"])
    )


def _summarize(raw: dict[str, float]) -> dict[str, object]:
    n = int(raw["n"])

    def mrows(ns: float) -> float:
        return (n / (ns * 1e-9)) / 1e6 if ns > 0 else 0.0

    speedup = raw["unfused_ns"] / raw["fused_ns"] if raw["fused_ns"] > 0 else 0.0
    return {
        "n": n,
        "unfused_mrows_per_sec": round(mrows(raw["unfused_ns"]), 1),
        "fused_mrows_per_sec": round(mrows(raw["fused_ns"]), 1),
        "fusion_speedup": round(speedup, 2),
    }


def run(sizes: list[int], clang: str) -> list[dict[str, object]]:
    with tempfile.TemporaryDirectory(prefix="lsfuse_") as tmp:
        exe = _build(clang, Path(tmp))
        summaries: list[dict[str, object]] = []
        for n in sizes:
            raw = _run_size(exe, n)
            if not _results_agree(raw):
                raise BenchmarkError(
                    f"fused and unfused disagree at n={n}; comparison is invalid"
                )
            summaries.append(_summarize(raw))
    return summaries


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--sizes",
        type=int,
        nargs="+",
        default=list(DEFAULT_SIZES),
        help="Row counts to sweep (default: 4k .. 1M).",
    )
    parser.add_argument("--clang", default="clang", help="C compiler to use.")
    parser.add_argument("--json", action="store_true", help="Emit JSON instead of a table.")
    parser.add_argument("--output", type=Path, help="Also write the JSON report to this path.")
    args = parser.parse_args()

    clang = shutil.which(args.clang)
    if clang is None:
        raise SystemExit(
            f"'{args.clang}' not found on PATH; this micro-benchmark requires clang."
        )

    results = run(sorted(set(args.sizes)), clang)
    payload = {"schema_version": 1, "kind": "fusion_probe", "results": results}

    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")

    if args.json:
        print(json.dumps(payload, indent=2))
        return 0

    print(f"Multi-stage fusion probe ({clang})")
    print(
        "unfused = one loop per stage (what codegen emits for accum groups today);\n"
        "fused = single loop, intermediates in registers (the optimizer's plan).\n"
        "speedup = unfused / fused = throughput a fusion-through-accum change recovers.\n"
    )
    print("| rows | unfused Mrows/s | fused Mrows/s | speedup |")
    print("| ---: | ---: | ---: | ---: |")
    for row in results:
        print(
            f"| {row['n']} | {row['unfused_mrows_per_sec']} "
            f"| {row['fused_mrows_per_sec']} | {row['fusion_speedup']}x |"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
