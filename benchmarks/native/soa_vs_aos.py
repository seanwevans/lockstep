#!/usr/bin/env python3
"""Quantify Lockstep's Struct-of-Arrays (SoA) memory layout win.

Lockstep decomposes every struct into parallel primitive arrays (SoA) rather
than laying out an array of whole structs (AoS). The README claims this
"maximizes cache line utilization and SIMD width." This micro-benchmark measures
that claim directly: it runs the *same* branchless particle kernel over the
*same* data in both layouts and reports the throughput difference across a sweep
of working-set sizes.

Two kernels model the two situations that matter:

* ``integrate`` reads and writes every field (a full physics step, like the
  ``particle_energy`` workload). Here SoA's win comes from vectorization -- its
  contiguous per-field arrays feed packed SIMD loads/stores, while AoS's
  interleaved 24-byte stride forces gathers or scalar fallback.
* ``energy`` reads only a subset of fields (velocity + mass) to accumulate
  kinetic energy. Here SoA additionally wins on bandwidth: AoS drags the unused
  position fields through cache on every access, SoA streams only what it reads.

Both layouts compute identical results (verified by matching checksums), so the
only variable is memory layout. Everything is built with ``clang -O3
-march=native``; absolute numbers are host-dependent, so read the *ratio*.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent

DEFAULT_SIZES = (1_000, 4_000, 16_000, 64_000, 256_000, 1_000_000)


class BenchmarkError(RuntimeError):
    pass


# A 6-float particle (24 bytes) -- the same shape as the particle_energy
# workload. The kernels below are straight-line and branchless, matching
# Lockstep's execution model, so per-row timing is data-independent.
_C_SOURCE = r"""/* Auto-generated by benchmarks/native/soa_vs_aos.py -- do not edit. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* Portability shim: the MSVC/UCRT toolchain used by clang on Windows lacks
   POSIX clock_gettime and C11 aligned_alloc, so provide equivalents. */
#if defined(_WIN32)
#include <windows.h>
#include <malloc.h>
static void *bench_aligned_alloc(size_t align, size_t size) {
    return _aligned_malloc(size, align);
}
static double bench_now_ns(void) {
    LARGE_INTEGER freq, ctr;
    QueryPerformanceFrequency(&freq);
    QueryPerformanceCounter(&ctr);
    return (double)ctr.QuadPart * 1e9 / (double)freq.QuadPart;
}
#else
#include <time.h>
static void *bench_aligned_alloc(size_t align, size_t size) {
    size_t rounded = (size + align - 1) & ~(align - 1);  /* C11 requires a multiple */
    return aligned_alloc(align, rounded);
}
static double bench_now_ns(void) {
    struct timespec t;
    clock_gettime(CLOCK_MONOTONIC, &t);
    return (double)t.tv_sec * 1e9 + (double)t.tv_nsec;
}
#endif

typedef struct { float px, py, vx, vy, mass, pad; } Particle;  /* AoS element */

typedef struct {
    float *px, *py, *vx, *vy, *mass;                           /* SoA columns */
} Columns;

static double now_ns(void) { return bench_now_ns(); }

/* ---- integrate: touches every field (full physics step) ---- */
static void integrate_aos(Particle *in, Particle *out, size_t n) {
    for (size_t i = 0; i < n; ++i) {
        out[i].px = in[i].px + in[i].vx;
        out[i].py = in[i].py + in[i].vy;
        out[i].vx = in[i].vx * 0.995f;
        out[i].vy = in[i].vy * 0.995f;
        out[i].mass = in[i].mass;
    }
}

static void integrate_soa(const Columns *in, const Columns *out, size_t n) {
    for (size_t i = 0; i < n; ++i) {
        out->px[i] = in->px[i] + in->vx[i];
        out->py[i] = in->py[i] + in->vy[i];
        out->vx[i] = in->vx[i] * 0.995f;
        out->vy[i] = in->vy[i] * 0.995f;
        out->mass[i] = in->mass[i];
    }
}

/* ---- energy: reads only vx, vy, mass (subset of fields) ---- */
static float energy_aos(const Particle *in, size_t n) {
    float acc = 0.0f;
    for (size_t i = 0; i < n; ++i)
        acc += 0.5f * in[i].mass * (in[i].vx * in[i].vx + in[i].vy * in[i].vy);
    return acc;
}

static float energy_soa(const Columns *in, size_t n) {
    float acc = 0.0f;
    for (size_t i = 0; i < n; ++i)
        acc += 0.5f * in->mass[i] * (in->vx[i] * in->vx[i] + in->vy[i] * in->vy[i]);
    return acc;
}

static Columns alloc_columns(size_t n) {
    Columns c;
    c.px = bench_aligned_alloc(64, n * sizeof(float));
    c.py = bench_aligned_alloc(64, n * sizeof(float));
    c.vx = bench_aligned_alloc(64, n * sizeof(float));
    c.vy = bench_aligned_alloc(64, n * sizeof(float));
    c.mass = bench_aligned_alloc(64, n * sizeof(float));
    return c;
}

int main(int argc, char **argv) {
    if (argc < 3) { fprintf(stderr, "usage: %s N ITERS\n", argv[0]); return 2; }
    size_t n = (size_t)strtoull(argv[1], NULL, 10);
    int iters = atoi(argv[2]);

    Particle *aos_in = bench_aligned_alloc(64, n * sizeof(Particle));
    Particle *aos_out = bench_aligned_alloc(64, n * sizeof(Particle));
    Columns soa_in = alloc_columns(n);
    Columns soa_out = alloc_columns(n);
    if (!aos_in || !aos_out || !soa_in.px || !soa_out.px) {
        fprintf(stderr, "alloc failed\n"); return 2;
    }

    for (size_t i = 0; i < n; ++i) {
        float px = (float)(i % 997) * 0.01f;
        float py = (float)(i % 991) * 0.02f;
        float vx = 1.0f - (float)(i % 100) * 0.01f;
        float vy = 0.5f - (float)(i % 50) * 0.01f;
        float mass = 0.5f + (float)(i % 10) * 0.1f;
        aos_in[i].px = px; aos_in[i].py = py; aos_in[i].vx = vx;
        aos_in[i].vy = vy; aos_in[i].mass = mass; aos_in[i].pad = 0.0f;
        soa_in.px[i] = px; soa_in.py[i] = py; soa_in.vx[i] = vx;
        soa_in.vy[i] = vy; soa_in.mass[i] = mass;
    }

    volatile float sink = 0.0f;
    double t;

    /* integrate */
    for (int w = 0; w < 3; ++w) integrate_aos(aos_in, aos_out, n);
    t = now_ns();
    for (int k = 0; k < iters; ++k) integrate_aos(aos_in, aos_out, n);
    double integrate_aos_ns = (now_ns() - t) / iters;
    sink += aos_out[n - 1].px;

    for (int w = 0; w < 3; ++w) integrate_soa(&soa_in, &soa_out, n);
    t = now_ns();
    for (int k = 0; k < iters; ++k) integrate_soa(&soa_in, &soa_out, n);
    double integrate_soa_ns = (now_ns() - t) / iters;
    sink += soa_out.px[n - 1];

    float integrate_check_aos = aos_out[n / 2].px + aos_out[n / 2].vx;
    float integrate_check_soa = soa_out.px[n / 2] + soa_out.vx[n / 2];

    /* energy */
    float e_aos = 0.0f, e_soa = 0.0f;
    for (int w = 0; w < 3; ++w) e_aos = energy_aos(aos_in, n);
    t = now_ns();
    for (int k = 0; k < iters; ++k) e_aos = energy_aos(aos_in, n);
    double energy_aos_ns = (now_ns() - t) / iters;

    for (int w = 0; w < 3; ++w) e_soa = energy_soa(&soa_in, n);
    t = now_ns();
    for (int k = 0; k < iters; ++k) e_soa = energy_soa(&soa_in, n);
    double energy_soa_ns = (now_ns() - t) / iters;
    sink += e_aos + e_soa;
    (void)sink;

    printf(
        "{\"n\": %zu, "
        "\"integrate_aos_ns\": %.1f, \"integrate_soa_ns\": %.1f, "
        "\"energy_aos_ns\": %.1f, \"energy_soa_ns\": %.1f, "
        "\"integrate_check_aos\": %.4f, \"integrate_check_soa\": %.4f, "
        "\"energy_aos\": %.3f, \"energy_soa\": %.3f}\n",
        n, integrate_aos_ns, integrate_soa_ns, energy_aos_ns, energy_soa_ns,
        integrate_check_aos, integrate_check_soa, e_aos, e_soa);
    return 0;
}
"""


def _iterations_for(n: int) -> int:
    """More repeats for small n so every size gets a stable, multi-ms sample."""

    return max(20, min(20000, 200_000_000 // max(n, 1)))


def _build(
    clang: str,
    work_dir: Path,
    *,
    label: str = "native",
    extra_flags: tuple[str, ...] = (),
    check: bool = True,
) -> Path | None:
    src = work_dir / "soa_vs_aos.c"
    exe = work_dir / f"soa_vs_aos_{label}"
    src.write_text(_C_SOURCE, encoding="utf-8")
    # -ffast-math mirrors Lockstep's codegen: the backend emits reduction loops
    # with `fast` flags so LLVM may reassociate float adds into a vector tree.
    # Without it a scalar float reduction serializes on its accumulator and no
    # layout can vectorize it, which would understate the SoA bandwidth win.
    cmd = [
        clang,
        "-O3",
        "-march=native",
        *extra_flags,
        "-ffast-math",
        str(src),
        "-o",
        str(exe),
        "-lm",
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        if not check:
            return None
        raise BenchmarkError(f"clang failed ({proc.returncode})\n{proc.stderr.strip()}")
    return exe


def _emits_gather_scatter(clang: str, work_dir: Path) -> bool:
    """Does the native build lower a kernel to gather/scatter instructions?

    Only the AoS kernels can: their interleaved stride is what pushes the
    vectorizer onto ``vgather*``/``vscatter*``, while the SoA columns are
    contiguous unit-stride loads and stores. So a hit anywhere in this
    translation unit means the AoS baseline is paying for gather/scatter, which
    is a *codegen* cost rather than a property of the memory layout -- and on
    Intel those instructions are slow enough to dominate the comparison.

    Scatter is the expensive half and is AVX-512-only, which is why the control
    build below is checked for scatter specifically: AVX2 still has gather.
    """
    src = work_dir / "soa_vs_aos.c"
    src.write_text(_C_SOURCE, encoding="utf-8")
    asm = work_dir / "soa_vs_aos.s"
    proc = subprocess.run(
        [
            clang,
            "-O3",
            "-march=native",
            "-ffast-math",
            "-S",
            str(src),
            "-o",
            str(asm),
        ],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        return False
    text = asm.read_text(encoding="utf-8", errors="replace")
    return "vgather" in text or "vscatter" in text


def _run_size(exe: Path, n: int) -> dict[str, float]:
    iters = _iterations_for(n)
    run = subprocess.run(
        [str(exe), str(n), str(iters)], capture_output=True, text=True, timeout=300
    )
    if run.returncode != 0:
        raise BenchmarkError(f"probe failed for n={n} ({run.returncode})\n{run.stderr.strip()}")
    try:
        return json.loads(run.stdout.strip().splitlines()[-1])
    except (json.JSONDecodeError, IndexError) as exc:
        raise BenchmarkError(f"could not parse probe output for n={n}: {run.stdout!r}") from exc


def _summarize(raw: dict[str, float]) -> dict[str, object]:
    n = int(raw["n"])

    def mrows(ns: float) -> float:
        return (n / (ns * 1e-9)) / 1e6 if ns > 0 else 0.0

    integrate_speedup = (
        raw["integrate_aos_ns"] / raw["integrate_soa_ns"]
        if raw["integrate_soa_ns"] > 0
        else 0.0
    )
    energy_speedup = (
        raw["energy_aos_ns"] / raw["energy_soa_ns"] if raw["energy_soa_ns"] > 0 else 0.0
    )
    return {
        "n": n,
        "integrate_aos_mrows_per_sec": round(mrows(raw["integrate_aos_ns"]), 1),
        "integrate_soa_mrows_per_sec": round(mrows(raw["integrate_soa_ns"]), 1),
        "integrate_soa_speedup": round(integrate_speedup, 2),
        "energy_aos_mrows_per_sec": round(mrows(raw["energy_aos_ns"]), 1),
        "energy_soa_mrows_per_sec": round(mrows(raw["energy_soa_ns"]), 1),
        "energy_soa_speedup": round(energy_speedup, 2),
    }


def _summarize_no_scatter(raw: dict[str, float]) -> dict[str, object]:
    """Same metrics from the gather/scatter-free build, suffixed."""
    base = _summarize(raw)
    return {
        f"{key}_no_scatter": value for key, value in base.items() if key != "n"
    }


def _results_agree(raw: dict[str, float]) -> bool:
    def close(a: float, b: float) -> bool:
        scale = max(1.0, abs(a), abs(b))
        return abs(a - b) <= 1e-3 * scale

    return close(raw["integrate_check_aos"], raw["integrate_check_soa"]) and close(
        raw["energy_aos"], raw["energy_soa"]
    )


def run(
    sizes: list[int],
    clang: str,
    *,
    no_scatter_flags: tuple[str, ...] = ("-mno-avx512f",),
    skip_no_scatter: bool = False,
) -> tuple[list[dict[str, object]], dict[str, object]]:
    """Measure the layout win, and separate it from gather/scatter codegen.

    On an AVX-512 host clang lowers the AoS kernels to ``vgatherqps`` /
    ``vscatterqps``, which are slow enough to dominate the comparison and make
    the layout look far more decisive than it is. Rebuilding the *same source*
    with scatter unavailable leaves SoA essentially unchanged while AoS speeds
    up several-fold, so the second build is what separates "SoA is a better
    layout" from "clang picked scatter for the AoS store".
    """
    with tempfile.TemporaryDirectory(prefix="lssoa_") as tmp:
        work = Path(tmp)
        exe = _build(clang, work)
        assert exe is not None  # check=True raises instead of returning None
        uses_gather_scatter = _emits_gather_scatter(clang, work)

        no_scatter_exe: Path | None = None
        if uses_gather_scatter and not skip_no_scatter:
            no_scatter_exe = _build(
                clang,
                work,
                label="noscatter",
                extra_flags=no_scatter_flags,
                check=False,
            )
            if no_scatter_exe is not None and _emits_scatter_with(
                clang, work, no_scatter_flags
            ):
                # The flags did not actually remove scatter; reporting the build
                # as a scatter-free control would be a lie.
                no_scatter_exe = None

        summaries: list[dict[str, object]] = []
        for n in sizes:
            raw = _run_size(exe, n)
            if not _results_agree(raw):
                raise BenchmarkError(
                    f"AoS and SoA disagree at n={n}; layout comparison is invalid"
                )
            summary = _summarize(raw)
            if no_scatter_exe is not None:
                ns_raw = _run_size(no_scatter_exe, n)
                if not _results_agree(ns_raw):
                    raise BenchmarkError(
                        f"AoS and SoA disagree at n={n} in the no-scatter build; "
                        "layout comparison is invalid"
                    )
                summary.update(_summarize_no_scatter(ns_raw))
            summaries.append(summary)

    meta: dict[str, object] = {
        "aos_uses_gather_scatter": uses_gather_scatter,
        "no_scatter_build": no_scatter_exe is not None,
        "no_scatter_flags": list(no_scatter_flags) if no_scatter_exe is not None else [],
    }
    return summaries, meta


def _emits_scatter_with(
    clang: str, work_dir: Path, extra_flags: tuple[str, ...]
) -> bool:
    """Does a build with ``extra_flags`` still emit scatter stores?"""
    src = work_dir / "soa_vs_aos.c"
    asm = work_dir / "soa_vs_aos_noscatter.s"
    proc = subprocess.run(
        [clang, "-O3", "-march=native", *extra_flags, "-ffast-math", "-S",
         str(src), "-o", str(asm)],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        return True  # cannot prove it is gone
    return "vscatter" in asm.read_text(encoding="utf-8", errors="replace")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--sizes",
        type=int,
        nargs="+",
        default=list(DEFAULT_SIZES),
        help="Row counts to sweep (default: 1k .. 1M).",
    )
    parser.add_argument("--clang", default="clang", help="C compiler to use.")
    parser.add_argument("--json", action="store_true", help="Emit JSON instead of a table.")
    parser.add_argument("--output", type=Path, help="Also write the JSON report to this path.")
    parser.add_argument(
        "--no-scatter-flags",
        nargs="+",
        default=["-mno-avx512f"],
        help=(
            "Flags for the control build that denies the vectorizer "
            "gather/scatter (default: -mno-avx512f, i.e. x86). Only used when "
            "the native build actually emits them."
        ),
    )
    parser.add_argument(
        "--skip-no-scatter",
        action="store_true",
        help="Report only the native build, without the gather/scatter control.",
    )
    args = parser.parse_args()

    clang = shutil.which(args.clang)
    if clang is None:
        raise SystemExit(
            f"'{args.clang}' not found on PATH; this micro-benchmark requires clang."
        )

    results, meta = run(
        sorted(set(args.sizes)),
        clang,
        no_scatter_flags=tuple(args.no_scatter_flags),
        skip_no_scatter=args.skip_no_scatter,
    )
    payload = {"schema_version": 2, "kind": "soa_vs_aos", "results": results, **meta}

    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")

    if args.json:
        print(json.dumps(payload, indent=2))
        return 0

    print(f"SoA vs AoS layout micro-benchmark ({clang})")
    print("Mrows/s per layout; speedup = SoA / AoS (higher = bigger SoA win).\n")
    print(
        "| rows | integrate AoS | integrate SoA | speedup | energy AoS | energy SoA | speedup |"
    )
    print("| ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    for row in results:
        print(
            f"| {row['n']} | {row['integrate_aos_mrows_per_sec']} "
            f"| {row['integrate_soa_mrows_per_sec']} | {row['integrate_soa_speedup']}x "
            f"| {row['energy_aos_mrows_per_sec']} | {row['energy_soa_mrows_per_sec']} "
            f"| {row['energy_soa_speedup']}x |"
        )

    if meta["no_scatter_build"]:
        flags = " ".join(str(f) for f in meta["no_scatter_flags"])  # type: ignore[union-attr]
        print()
        print(
            f"The AoS kernels lower to gather/scatter on this host. Same source "
            f"rebuilt with `{flags}`, which denies the vectorizer\n"
            "scatter (the expensive, AVX-512-only half) -- the residual gap is "
            "much closer to the layout effect proper:"
        )
        print()
        print(
            "| rows | integrate AoS | integrate SoA | speedup | energy AoS | energy SoA | speedup |"
        )
        print("| ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
        for row in results:
            print(
                f"| {row['n']} | {row['integrate_aos_mrows_per_sec_no_scatter']} "
                f"| {row['integrate_soa_mrows_per_sec_no_scatter']} "
                f"| {row['integrate_soa_speedup_no_scatter']}x "
                f"| {row['energy_aos_mrows_per_sec_no_scatter']} "
                f"| {row['energy_soa_mrows_per_sec_no_scatter']} "
                f"| {row['energy_soa_speedup_no_scatter']}x |"
            )
    elif meta["aos_uses_gather_scatter"]:
        print()
        print(
            "NOTE: the AoS kernels lower to gather/scatter on this host, so the "
            "speedups above\nconflate that codegen cost with the layout effect, "
            "but the control build was\nunavailable (flags rejected, or they did "
            "not remove the instructions)."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
